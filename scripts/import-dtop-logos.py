#!/usr/bin/env python3
"""Import dtop's bundled app logos and image-matching tables into the widget.

Usage: scripts/import-dtop-logos.py <dtop checkout>

Copies <dtop>/assets/app-logos/*.png to it.df.dtop/contents/images/app-logos/ and writes
it.df.dtop/contents/code/logodata.js from <dtop>/src/ui/app_logos_data.rs. Re-run to update.
"""
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEST_IMAGES = ROOT / "it.df.dtop/contents/images/app-logos"
DEST_DATA = ROOT / "it.df.dtop/contents/code/logodata.js"


def table(source, name):
    m = re.search(r"static " + name + r": [^=]+= &\[(.*?)\n\];", source, re.S)
    if not m:
        sys.exit("table %s not found" % name)
    return m.group(1)


def strings(body):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', body)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    dtop = pathlib.Path(sys.argv[1])
    source = (dtop / "src/ui/app_logos_data.rs").read_text()
    commit = subprocess.run(["git", "-C", str(dtop), "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()

    logos = [s for s in strings(table(source, "LOGOS")) if not s.startswith("../")]
    alias_pairs = re.findall(r'\(\s*"([^"]+)",\s*"([^"]+)",?\s*\)', table(source, "ALIASES"))
    data = {
        "LOGOS": logos,
        "ALIASES": {a: b for a, b in alias_pairs},
        "DISTRIBUTORS": strings(table(source, "DISTRIBUTORS")),
        "GENERIC": strings(table(source, "GENERIC")),
        "SUFFIXES": strings(table(source, "SUFFIXES")),
    }

    if DEST_IMAGES.exists():
        shutil.rmtree(DEST_IMAGES)
    DEST_IMAGES.mkdir(parents=True)
    for slug in logos:
        shutil.copyfile(dtop / "assets/app-logos" / (slug + ".png"), DEST_IMAGES / (slug + ".png"))
    readme = (dtop / "assets/app-logos/README.md").read_text()
    (DEST_IMAGES / "README.md").write_text(
        "Copied from dtop (https://github.com/amir20/dtop, MIT, Copyright (c) 2025 Amir Raminfar) "
        "commit %s by scripts/import-dtop-logos.py; don't edit by hand.\n\ndtop's notes:\n\n%s" % (commit, readme))

    lines = ["// @generated by scripts/import-dtop-logos.py from dtop %s (MIT). Do not edit." % commit,
             "// Logo slugs and image-matching tables of dtop's src/ui/app_logos_data.rs."]
    for key in ["LOGOS", "ALIASES", "DISTRIBUTORS", "GENERIC", "SUFFIXES"]:
        lines.append("var %s = %s;" % (key, json.dumps(data[key], ensure_ascii=False)))
    lines += ["",
              'if (typeof module !== "undefined" && module.exports) {',
              "    module.exports = { LOGOS: LOGOS, ALIASES: ALIASES, DISTRIBUTORS: DISTRIBUTORS, GENERIC: GENERIC, SUFFIXES: SUFFIXES };",
              "}", ""]
    DEST_DATA.write_text("\n".join(lines))
    print("%d logos, %d aliases" % (len(logos), len(alias_pairs)))


if __name__ == "__main__":
    main()
